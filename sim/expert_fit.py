"""Fit the constants sim/expert.py takes from the demonstrations and write them to sim/expert_sag.py.

Sag: under gravity the joint PD settles short of its command. The generator compensates (motion_choices
`equilibrium_command_compensation`), so on static rows leader - observation is the offset a command needs to reach
a pose. Model per arm and joint: offset = W^T [1, sin q, cos q] (q = the 7 reached joints), least squares over the
static rows (max |dq| < 2e-5 rad per tick) of the training split.

Posture range: per arm and joint, the min and max of all rows of the same episodes; sim/expert.py bounds its IK to
it (plus a margin) so that it stays on the demos' elbow branch.

Run: .venv/bin/python sim/expert_fit.py [--episodes 6]
"""
import argparse
import json
import sys
from pathlib import Path

import h5py
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from jenga.paths import DATA_ROOT as DATA  # noqa: E402  env JENGA_DATA_ROOT


def features(q7: np.ndarray) -> np.ndarray:
    q7 = np.atleast_2d(q7)
    return np.c_[np.ones(len(q7)), np.sin(q7), np.cos(q7)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", type=int, default=6, help="training episodes per variant")
    args = ap.parse_args()
    split = json.loads((ROOT / "runs/prep/split.json").read_text())
    X, Y, Q = [], [], []
    for sp in split["tasks"].values():
        for rel in sp["train"][:args.episodes]:
            with h5py.File(DATA / rel) as f:
                q, lead = f["observations/qpos"][:].astype(float), f["leader/qpos"][:].astype(float)
            Q.append(q)
            still = np.r_[np.inf, np.abs(np.diff(q, axis=0)).max(1)] < 2e-5
            X.append(q[still][::3])
            Y.append((lead - q)[still][::3])
    X, Y = np.concatenate(X), np.concatenate(Y)
    out, rng, Q = {}, {}, np.concatenate(Q)
    for k, arm in enumerate(("left", "back")):
        F, d = features(X[:, 8 * k:8 * k + 7]), Y[:, 8 * k:8 * k + 7]
        W, *_ = np.linalg.lstsq(F, d, rcond=None)
        res = d - F @ W
        print(arm, "rows", len(d), "raw std mrad", np.round(d.std(0) * 1e3, 2), "residual std mrad",
              np.round(res.std(0) * 1e3, 2))
        out[arm] = np.round(W, 6).tolist()
        rng[arm] = np.round([Q[:, 8 * k:8 * k + 7].min(0), Q[:, 8 * k:8 * k + 7].max(0)], 3).astype(float).tolist()
        print(arm, "range", rng[arm])
    body = (f'"""Generated by sim/expert_fit.py ({len(X)} static rows): per arm, W [15, 7] with '
            'command - reached = [1, sin q, cos q] @ W."""\n'
            f"SAG = {json.dumps(out)}\n"
            f"# per arm [min, max] of the 7 joints over {len(Q)} rows of the same episodes\nQPOS_RANGE = {json.dumps(rng)}\n")
    (ROOT / "sim/expert_sag.py").write_text(body)


if __name__ == "__main__":
    main()
